def parse_front_matter(content: str) -> dict[str, Any]:
    """Parse TOML front matter delimited by '+++' markers."""
    match = re.match(r"^\+\+\+\s*\n(.*?)\n\+\+\+\s*\n", content, re.DOTALL)
    if not match:
        raise ValueError("No TOML front matter found (expected +++ block)")
    return tomllib.loads(match.group(1))


def load_policy(trigger: str) -> dict[str, Any]:
    # Policies are named like H01-task-specification.md, H02-context-artifact.md, etc.
    # Require an exact prefix match "<trigger>-" to avoid ambiguous globs.
    candidates = list(POLICIES_DIR.glob(f"{trigger}-*.md"))
    if not candidates:
        candidates = list(POLICIES_DIR.glob(f"{trigger.lower()}-*.md"))
    if not candidates:
        raise FileNotFoundError(f"Policy not found for trigger {trigger}")
    if len(candidates) > 1:
        raise FileNotFoundError(
            f"Multiple policies found for trigger {trigger}: {', '.join(str(c) for c in candidates)}"
        )

    policy_path = candidates[0]
    content = policy_path.read_text(encoding="utf-8")
    meta = parse_front_matter(content)
    meta["_source"] = str(policy_path)
    return meta


def find_section_headings(content: str) -> set[str]:
    """Find all Markdown ## headings in the content."""
    headings: set[str] = set()
    for line in content.splitlines():
        match = re.match(r"^##\s+(.+?)\s*$", line)
        if match:
            headings.add(match.group(1).strip())
    return headings


def extract_section(content: str, section_name: str) -> str:
    """Extract the content of a Markdown ## section until the next ## heading."""
    pattern = rf"^##\s+{re.escape(section_name)}\s*\n(.*?)(?=^##\s|\Z)"
    match = re.search(pattern, content, re.MULTILINE | re.DOTALL)
    if not match:
        return ""
    return match.group(1).strip()


def safe_yaml_load(text: str) -> dict[str, Any] | None:
    """Parse a minimal subset of YAML without external dependencies.

    Supports nested mappings, lists, strings (quoted or unquoted),
    booleans, nulls, numbers and empty lists. Returns None if the
    top-level result is not a dict.

    Known limitations: does not support multiline values, lists of lists,
    quoted keys, or escape sequences. Intended only for machine-readable
    YAML blocks generated by the protocol.
    """
    lines = text.splitlines()
    items: list[tuple[int, str]] = []
    for line in lines:
        stripped = line.strip()
        if not stripped or stripped.startswith("#"):
            continue
        indent = len(line) - len(line.lstrip())
        items.append((indent, stripped))

    if not items:
        return None

    def parse_scalar(value: str) -> Any:
        value = value.strip()
        if not value:
            return ""
        if (value.startswith('"') and value.endswith('"')) or (
            value.startswith("'") and value.endswith("'")
        ):
            return value[1:-1]
        lowered = value.lower()
        if lowered == "true":
            return True
        if lowered == "false":
            return False
        if lowered in ("null", "~"):
            return None
        if value == "[]":
            return []
        try:
            if "." in value:
                return float(value)
            return int(value)
        except ValueError:
            return value

    def parse_block(
        data: list[tuple[int, str]], start: int, base_indent: int
    ) -> tuple[Any, int]:
        if start >= len(data):
            return {}, start

        idx = start
        while idx < len(data) and data[idx][0] <= base_indent:
            idx += 1
        if idx >= len(data):
            return {}, start

        first_indent, first_content = data[idx]

        if first_content.startswith("- "):
            result: list[Any] = []
            while idx < len(data):
                indent, content = data[idx]
                if indent < first_indent:
                    break
                if indent > first_indent or not content.startswith("- "):
                    idx += 1
                    continue
                item_text = content[2:].strip()

                if ":" in item_text:
                    sub_data: list[tuple[int, str]] = [(0, item_text)]
                    next_idx = idx + 1
                    while next_idx < len(data) and data[next_idx][0] > first_indent:
                        sub_data.append(
                            (
                                data[next_idx][0] - first_indent - 2,
                                data[next_idx][1],
                            )
                        )
                        next_idx += 1
                    sub_result, _ = parse_block(sub_data, 0, -1)
                    result.append(sub_result)
                    idx = next_idx
                else:
                    result.append(parse_scalar(item_text))
                    idx += 1
            return result, idx

        result: dict[str, Any] = {}
        while idx < len(data):
            indent, content = data[idx]
            if indent < first_indent:
                break
            if indent > first_indent or ":" not in content:
                idx += 1
                continue
            key, val = content.split(":", 1)
            key = key.strip()
            val = val.strip()

            if val == "":
                next_idx = idx + 1
                nested, next_idx = parse_block(data, next_idx, indent)
                result[key] = nested
                idx = next_idx
            elif val == "[]":
                result[key] = []
                idx += 1
            else:
                result[key] = parse_scalar(val)
                idx += 1
        return result, idx

    try:
        parsed, _ = parse_block(items, 0, -1)
    except Exception:
        return None
    if not isinstance(parsed, dict):
        return None
    return parsed


def extract_yaml_block(content: str, section_name: str) -> dict[str, Any] | None:
    """Extract the first ```yaml block from a given ## section.

    Returns the parsed dict or None if there is no block, it is not
    parsable, or it is not a dict.
    """
    section = extract_section(content, section_name)
    if not section:
        return None
    match = re.search(r"```yaml\n(.*?)\n```", section, re.DOTALL)
    if not match:
        return None
    return safe_yaml_load(match.group(1))


def validate_h07_scope_compliance(content: str) -> list[CheckResult]:
    checks: list[CheckResult] = []
    data = extract_yaml_block(content, "Scope Compliance")
    if data is None:
        checks.append(
            CheckResult(
                id="scope_yaml_parsable",
                result="FAIL",
                evidence="No valid YAML block found in ## Scope Compliance",
            )
        )
        return checks

    checks.append(
        CheckResult(
            id="scope_yaml_parsable", result="PASS", evidence="YAML block parsed"
        )
    )

    scope = data.get("scope_compliance", {})
    scope_respected = scope.get("scope_respected")
    unplanned = scope.get("unplanned_changes", None)
    authorized = scope.get("user_authorized_extra_work", None)

    checks.append(
        CheckResult(
            id="scope_respected_true",
            result="PASS" if scope_respected is True else "FAIL",
            evidence=f"scope_respected={scope_respected}",
        )
    )
    checks.append(
        CheckResult(
            id="unplanned_changes_empty",
            result=(
                "PASS"
                if isinstance(unplanned, list) and len(unplanned) == 0
                else "FAIL"
            ),
            evidence=f"unplanned_changes={unplanned}",
        )
    )
    checks.append(
        CheckResult(
            id="no_unauthorized_extra_work",
            result="PASS" if authorized is False else "FAIL",
            evidence=f"user_authorized_extra_work={authorized}",
        )
    )
    return checks


