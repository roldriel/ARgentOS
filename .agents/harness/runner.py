def _is_compound_criterion(text: str) -> bool:
    """Return True if the criterion joins multiple independent actions or conditions.

    A criterion is compound when "and" or "or" separate independent actions
    ("create X and send Y") or conditions ("validate A or B"). It is not compound
    when those words enumerate values within the same domain ("return HTTP 200 or
    201", "accept JSON and XML").
    """
    if ";" in text:
        return True

    normalized = re.sub(r"\s+", " ", text.strip().lower())
    if not re.search(r"\band\b|\bor\b", normalized):
        return False

    # Enumerations of values within the same domain are not compound.
    value_patterns = [
        r"\b(?:get|post|put|patch|delete|head|options)(?:\s+(?:and|or)\s+(?:get|post|put|patch|delete|head|options))+\b",
        r"\b(?:json|xml|yaml|csv|html|plain text|text/plain|application/json|application/xml)(?:\s+(?:and|or)\s+(?:json|xml|yaml|csv|html|plain text|text/plain|application/json|application/xml))+\b",
        r"\b(?:true|false)(?:\s+(?:and|or)\s+(?:true|false))+\b",
        r"\b(?:admin|user|guest|reader|writer|editor|owner)(?:\s+(?:and|or)\s+(?:admin|user|guest|reader|writer|editor|owner))+\b",
        r"\b\d+(?:\s+(?:and|or)\s+\d+)+\b",
    ]
    for pattern in value_patterns:
        if re.search(pattern, normalized):
            # Ensure the whole criterion is not an enumeration; remove the matched part and
            # check that no remaining "and"/"or" join separate actions.
            remaining = re.sub(pattern, "", normalized, count=1).strip()
            if not re.search(r"\band\b|\bor\b", remaining):
                return False

    tokens = re.findall(r"[a-z0-9/]+|\d+", normalized)
    for i, token in enumerate(tokens):
        if token in ("and", "or"):
            # "and"/"or" followed by an action verb indicates a separate action.
            if i + 1 < len(tokens) and tokens[i + 1] in _ACTION_VERBS:
                return True
            # "and"/"or" between a verb and a non-value-domain token indicates multiple
            # independent conditions/actions.
            if i - 1 >= 0 and tokens[i - 1] in _ACTION_VERBS:
                if i + 1 < len(tokens) and tokens[i + 1] not in _VALUE_DOMAIN_TOKENS:
                    return True
    return False


def validate_ears(section_content: str) -> list[CheckResult]:
    """Validate that each bullet in the section follows an EARS pattern and is atomic."""
    checks: list[CheckResult] = []
    bullets = [
        line.strip()
        for line in section_content.splitlines()
        if re.match(r"^[-*]\s+", line.strip())
    ]

    if not bullets:
        checks.append(
            CheckResult(
                id="ears_criteria_present",
                result="FAIL",
                evidence="No acceptance criteria bullets found",
            )
        )
        return checks

    checks.append(
        CheckResult(
            id="ears_criteria_present",
            result="PASS",
            evidence=f"Found {len(bullets)} acceptance criterion/criteria",
        )
    )

    # EARS patterns
    patterns = [
        (r"^The\s+.+\s+shall\s+.+$", "ubiquitous"),
        (r"^When\s+.+\s*,\s*the\s+.+\s+shall\s+.+$", "event-driven"),
        (r"^While\s+.+\s*,\s*the\s+.+\s+shall\s+.+$", "state-driven"),
        (r"^If\s+.+\s*,\s*then\s+the\s+.+\s+shall\s+.+$", "unwanted-behavior"),
        (r"^Where\s+.+\s*,\s*the\s+.+\s+shall\s+.+$", "optional-feature"),
    ]

    for idx, bullet in enumerate(bullets, start=1):
        # Remove leading bullet marker
        text = re.sub(r"^[-*]\s+", "", bullet)

        # Check compound
        if _is_compound_criterion(text):
            checks.append(
                CheckResult(
                    id=f"ears_atomic_{idx}",
                    result="FAIL",
                    evidence=f"Criterion {idx} is compound: {text[:80]}",
                )
            )
            continue

        matched = any(re.match(pattern, text, re.IGNORECASE) for pattern, _ in patterns)
        if matched:
            checks.append(
                CheckResult(
                    id=f"ears_pattern_{idx}",
                    result="PASS",
                    evidence=f"Criterion {idx} follows an EARS pattern",
                )
            )
        else:
            checks.append(
                CheckResult(
                    id=f"ears_pattern_{idx}",
                    result="FAIL",
                    evidence=f"Criterion {idx} does not follow an EARS pattern: {text[:80]}",
                )
            )

    return checks


def validate_sections(
    artifact_content: str, required_sections: list[str]
) -> list[CheckResult]:
    headings = find_section_headings(artifact_content)
    checks: list[CheckResult] = []
    for section in required_sections:
        # Normalize comparison: ignore case and allow title-case variations
        normalized = {h.lower(): h for h in headings}
        if section.lower() in normalized:
            checks.append(
                CheckResult(
                    id=f"has_section_{section.lower().replace(' ', '_')}",
                    result="PASS",
                    evidence=f"Section '{normalized[section.lower()]}' found",
                )
            )
        else:
            checks.append(
                CheckResult(
                    id=f"has_section_{section.lower().replace(' ', '_')}",
                    result="FAIL",
                    evidence=f"Required section '{section}' not found",
                )
            )
    return checks


def iteration_dirs(session_uuid: str) -> list[Path]:
    """Return sorted list of numeric iteration directories for a session."""
    session_dir = ARTIFACTS_DIR / session_uuid
    if not session_dir.exists():
        return []
    dirs = [
        p for p in session_dir.iterdir() if p.is_dir() and re.fullmatch(r"\d+", p.name)
    ]
    return sorted(dirs, key=lambda p: int(p.name))


def _find_artifact_in_iter(iter_dir: Path, artifact_name: str) -> Path | None:
    """Look for an artifact by its base name inside an iteration folder.

    Accepts files named either `<artifact_name>` or `<prefix>-<artifact_name>`.
    Returns the first match found, or None.
    """
    if not iter_dir.exists():
        return None
    for candidate in iter_dir.iterdir():
        if not candidate.is_file():
            continue
        if candidate.name == artifact_name or candidate.name.endswith(
            f"-{artifact_name}"
        ):
            return candidate
    return None


def artifact_path(
    session_uuid: str, artifact_name: str, iteration: str | None = None
) -> Path:
    """Resolve the path to an artifact inside a numbered iteration folder.

    Artifacts are expected to be named either `<artifact_name>` or
    `<order>-<artifact_name>` (e.g. `01-TASK_ANALYSIS.md`). The order prefix
    reflects the generation/reading order within the iteration and is not
    derived from the iteration folder name.

    If iteration is provided, look in that folder. Otherwise scan iterations in
    descending order and return the latest match. If no match is found, return
    the path where the artifact is expected to be created (latest iteration, or
    iteration 00 if none exist).
    """
    session_dir = ARTIFACTS_DIR / session_uuid

    if iteration is not None:
        iter_dir = session_dir / iteration
        found = _find_artifact_in_iter(iter_dir, artifact_name)
        return found if found else iter_dir / artifact_name

    dirs = iteration_dirs(session_uuid)
    for iter_dir in reversed(dirs):
        found = _find_artifact_in_iter(iter_dir, artifact_name)
        if found:
            return found

    # Default target for creation: latest iteration or 00
    target_iter = dirs[-1].name if dirs else "00"
    return session_dir / target_iter / artifact_name


def report_path(session_uuid: str) -> Path:
    """Return the session-level HARNESS_REPORT.md path."""
    return ARTIFACTS_DIR / session_uuid / "HARNESS_REPORT.md"


def run_trigger(
    session_uuid: str, trigger: str, iteration: str | None = None
) -> HarnessResult:
    start = time.perf_counter()
    timestamp = datetime.now(timezone.utc).isoformat()

    def _finish(result: HarnessResult) -> HarnessResult:
        result.duration_ms = int((time.perf_counter() - start) * 1000)
        return result

    try:
        policy = load_policy(trigger)
    except FileNotFoundError as exc:
        return _finish(
            HarnessResult(
                trigger=trigger,
                transition="UNKNOWN",
                result="FAIL",
                timestamp=timestamp,
                error=str(exc),
            )
        )
    except ValueError as exc:
        return _finish(
            HarnessResult(
                trigger=trigger,
                transition=(
                    policy.get("transition", "UNKNOWN")
                    if "policy" in locals()
                    else "UNKNOWN"
                ),
                result="FAIL",
                timestamp=timestamp,
                error=str(exc),
            )
        )

    transition = policy.get("transition", "UNKNOWN")
    artifact_name = policy.get("artifact")
    validation_type = policy.get("validation_type", "artifact")
    required_sections = policy.get("required_sections", [])

    result = HarnessResult(
        trigger=trigger,
        transition=transition,
        result="PASS",
        artifact=(
            str(artifact_path(session_uuid, artifact_name, iteration))
            if artifact_name
            else None
        ),
        report=str(report_path(session_uuid)),
        timestamp=timestamp,
    )

    if validation_type == "artifact" and artifact_name:
        artifact = artifact_path(session_uuid, artifact_name, iteration)
        if not artifact.exists():
            result.checks.append(
                CheckResult(
                    id="artifact_exists",
                    result="FAIL",
                    evidence=f"Artifact not found: {artifact}",
                )
            )
            result.result = "FAIL"
        else:
            result.checks.append(
                CheckResult(
                    id="artifact_exists",
                    result="PASS",
                    evidence=f"Artifact found: {artifact}",
                )
            )
            content = artifact.read_text(encoding="utf-8")
            section_checks = validate_sections(content, required_sections)
            result.checks.extend(section_checks)
            if any(c.result == "FAIL" for c in section_checks):
                result.result = "FAIL"

    # EARS validation for acceptance criteria sections
    if policy.get("ears_validation") and artifact_name and result.artifact:
        artifact = artifact_path(session_uuid, artifact_name, iteration)
        if artifact.exists():
            content = artifact.read_text(encoding="utf-8")
            section_name = policy.get("ears_section", "Acceptance criteria")
            section_content = extract_section(content, section_name)
            if section_content:
                ears_checks = validate_ears(section_content)
                result.checks.extend(ears_checks)
                if any(c.result == "FAIL" for c in ears_checks):
                    result.result = "FAIL"
            else:
                result.checks.append(
                    CheckResult(
                        id="ears_section_found",
                        result="FAIL",
                        evidence=f"EARS section '{section_name}' not found",
                    )
                )
                result.result = "FAIL"

    # Rubric evaluation structural validation
    if policy.get("rubric_validation") and artifact_name and result.artifact:
        artifact = artifact_path(session_uuid, artifact_name, iteration)
        if artifact.exists():
            content = artifact.read_text(encoding="utf-8")
            rubric_set = expected_rubrics_for_session(session_uuid, iteration)
            rubric_checks, rubric_scores = validate_rubric_evaluation(
                content, rubric_set
            )
            result.checks.extend(rubric_checks)
            result.rubric_scores.update(rubric_scores)
            if any(c.result == "FAIL" for c in rubric_checks):
                result.result = "FAIL"

    # Semantic validation for specific triggers
    if policy.get("semantic_validation"):
        if trigger == "H01":
            semantic_checks = validate_h01_technical_approach(session_uuid, iteration)
            result.checks.extend(semantic_checks)
            if any(c.result == "FAIL" for c in semantic_checks):
                result.result = "FAIL"

        if trigger == "H07" and artifact_name and result.artifact:
            artifact = artifact_path(session_uuid, artifact_name, iteration)
            if artifact.exists():
                content = artifact.read_text(encoding="utf-8")
                semantic_checks = validate_h07_scope_compliance(content)
                result.checks.extend(semantic_checks)
                if any(c.result == "FAIL" for c in semantic_checks):
                    result.result = "FAIL"

        if trigger == "H06" and artifact_name and result.artifact:
            artifact = artifact_path(session_uuid, artifact_name, iteration)
            if artifact.exists():
                content = artifact.read_text(encoding="utf-8")
                semantic_checks = validate_h06_final_decision(content)
                semantic_checks += validate_h06_acceptance_criteria(content)
                result.checks.extend(semantic_checks)
                if any(c.result == "FAIL" for c in semantic_checks):
                    result.result = "FAIL"

        if trigger == "H05":
            semantic_checks = validate_h05_execution_summary(session_uuid, iteration)
            semantic_checks += validate_h05_technical_practice_evidence(
                session_uuid, iteration
            )
            result.checks.extend(semantic_checks)
            if any(c.result == "FAIL" for c in semantic_checks):
                result.result = "FAIL"

    return _finish(result)


def update_report(session_uuid: str, result: HarnessResult) -> None:
    report = report_path(session_uuid)
    report.parent.mkdir(parents=True, exist_ok=True)

    # Try to preserve existing entries; otherwise create a new report from template.
    existing_entries: list[dict[str, Any]] = []
    if report.exists():
        existing_report = report.read_text(encoding="utf-8")
        # Extract existing JSON entries embedded after each entry marker.
        for match in re.finditer(
            r"<!-- ENTRY: (\{.*?\}) -->", existing_report, re.DOTALL
        ):
            try:
                existing_entries.append(json.loads(match.group(1)))
            except json.JSONDecodeError:
                pass

    entry = {
        "timestamp": result.timestamp,
        "trigger": result.trigger,
        "transition": result.transition,
        "result": result.result,
        "checks": [
            {"id": c.id, "result": c.result, "evidence": c.evidence}
            for c in result.checks
        ],
        "artifact": result.artifact,
        "duration_ms": result.duration_ms,
        "rubric_scores": result.rubric_scores,
    }
    existing_entries.append(entry)

    # Rebuild report from template using our own structure.
    lines = [
        "# Harness Report",
        "",
        f"- Session UUID: `{session_uuid}`",
        f"- Last updated: `{result.timestamp}`",
        "",
        "## Summary",
        "",
        "| Trigger | Transition | Result | Timestamp |",
        "|---|---|---|---|",
    ]
    for e in existing_entries:
        lines.append(
            f"| {e['trigger']} | {e['transition']} | {e['result']} | {e['timestamp']} |"
        )

    lines.extend(
        [
            "",
            "## Entries",
            "",
        ]
    )

    for e in existing_entries:
        lines.append(f"### {e['trigger']}")
        lines.append("")
        lines.append(f"- Transition: `{e['transition']}`")
        lines.append(f"- Result: `{e['result']}`")
        lines.append(f"- Timestamp: `{e['timestamp']}`")
        if e.get("artifact"):
            lines.append(f"- Artifact checked: `{e['artifact']}`")
        lines.append("- Checks:")
        for check in e.get("checks", []):
            lines.append(
                f"  - `{check['id']}`: {check['result']} — {check['evidence']}"
            )
        lines.append("")
        # Embed machine-readable entry for future updates.
        lines.append(f"<!-- ENTRY: {json.dumps(e)} -->")
        lines.append("")

    # Aggregate metrics per trigger from all entries.
    metrics: dict[str, dict[str, Any]] = {}
    for e in existing_entries:
        trigger = e.get("trigger", "UNKNOWN")
        bucket = metrics.setdefault(
            trigger, {"invocations": 0, "pass": 0, "fail": 0, "duration_ms": 0}
        )
        bucket["invocations"] += 1
        if e.get("result") == "PASS":
            bucket["pass"] += 1
        else:
            bucket["fail"] += 1
        bucket["duration_ms"] += e.get("duration_ms", 0)

    lines.extend(
        [
            "",
            "## Metrics",
            "",
            "| Trigger | Invocations | PASS | FAIL | Avg Duration (ms) |",
            "|---|---|---|---|---|",
        ]
    )
    for trigger, bucket in sorted(metrics.items()):
        avg = (
            bucket["duration_ms"] // bucket["invocations"]
            if bucket["invocations"]
            else 0
        )
        lines.append(
            f"| {trigger} | {bucket['invocations']} | {bucket['pass']} | {bucket['fail']} | {avg} |"
        )

    # Aggregate rubric scores from the latest entry that has them.
    latest_scores: dict[str, str] = {}
    for e in reversed(existing_entries):
        if e.get("rubric_scores"):
            latest_scores = e["rubric_scores"]
            break

    if latest_scores:
        lines.extend(
            [
                "",
                "## Rubric Scores",
                "",
            ]
        )
        for rubric, score in sorted(latest_scores.items()):
            lines.append(f"- {rubric}: {score}")

    lines.extend(
        [
            "",
            "## Final Decision",
            "",
            f"- Last result: `{result.result}`",
            f"- Last trigger: `{result.trigger}`",
            "",
        ]
    )

    report.write_text("\n".join(lines), encoding="utf-8")


