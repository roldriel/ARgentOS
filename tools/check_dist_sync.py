#!/usr/bin/env python3
"""Verify that the ``dist`` branch is in sync with the ``protocol/`` payload.

``dist`` is the published, adoptable layout: ``.agents/`` + ``AGENTS.md`` at
its root, regenerated by CI (publish-dist) from ``master``. This checker lets
you verify the sync locally without waiting for CI. The comparison is made
against the committed state (``HEAD``), not the working tree, so it is not
affected by line-ending normalization (core.autocrlf). It compares:

1. Every file under ``protocol/.agents/`` exists in ``dist`` under
   ``.agents/`` with identical bytes.
2. ``dist:AGENTS.md`` is byte-identical to ``protocol/_AGENTS.md``.
3. ``dist`` contains no extra files beyond those two sources.

Usage: python tools/check_dist_sync.py [--root REPO_ROOT] [--branch dist]

Exit code: 0 when in sync, 1 otherwise (including a missing branch).
Standard library only (uses the git CLI).
"""

from __future__ import annotations

import argparse
import subprocess
import sys
from pathlib import Path

_DEFAULT_BRANCH = "dist"


def _git(root: Path, *args: str, text: bool = False):
    return subprocess.run(
        ["git", "-C", str(root), *args],
        capture_output=True,
        text=text,
    )


def collect_source(root: Path, ref: str = "HEAD") -> dict[str, bytes]:
    """Expected dist contents: path-in-dist -> bytes, from the committed
    payload (``<ref>:protocol/``). Reading blobs (not the working tree) keeps
    the comparison free of line-ending normalization noise."""
    listing = _git(root, "ls-tree", "-r", "--name-only", ref, "--", "protocol/",
                   text=True)
    if listing.returncode != 0:
        return {}
    expected: dict[str, bytes] = {}
    for name in listing.stdout.splitlines():
        rel = name.split("protocol/", 1)[1]
        blob = _git(root, "show", f"{ref}:{name}")
        if blob.returncode != 0:
            continue
        if rel.startswith(".agents/"):
            expected[rel] = blob.stdout
        elif rel == "_AGENTS.md":
            expected["AGENTS.md"] = blob.stdout
    return expected


def collect_dist(root: Path, branch: str) -> dict[str, bytes] | None:
    """Actual dist contents: path -> bytes. None when the branch is missing."""
    if _git(root, "rev-parse", "--verify", "--quiet", branch).returncode != 0:
        return None
    listing = _git(root, "ls-tree", "-r", "--name-only", branch, text=True)
    files: dict[str, bytes] = {}
    for name in listing.stdout.splitlines():
        blob = _git(root, "show", f"{branch}:{name}")
        if blob.returncode == 0:
            files[name] = blob.stdout
    return files


def diff(
    expected: dict[str, bytes], actual: dict[str, bytes]
) -> list[str]:
    """Human-readable list of sync issues between expected and actual."""
    issues: list[str] = []
    for path in sorted(expected):
        if path not in actual:
            issues.append(f"missing in dist: {path}")
        elif expected[path] != actual[path]:
            issues.append(f"content differs: {path}")
    for path in sorted(actual):
        if path not in expected:
            issues.append(f"extra in dist: {path}")
    return issues


def format_report(issues: list[str], branch: str) -> str:
    if not issues:
        return f"dist is in sync with protocol/ (branch `{branch}`)."
    lines = [f"dist out of sync (branch `{branch}`): {len(issues)} issue(s)"]
    lines.extend(f"- {issue}" for issue in issues)
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--root",
        type=Path,
        default=Path(__file__).resolve().parents[1],
        help="Repository root (default: parent of this script's directory).",
    )
    parser.add_argument(
        "--branch",
        default=_DEFAULT_BRANCH,
        help="Branch to compare against (default: dist).",
    )
    args = parser.parse_args(argv)
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    root = args.root.resolve()
    actual = collect_dist(root, args.branch)
    if actual is None:
        print(f"branch `{args.branch}` not found in {root}")
        return 1
    issues = diff(collect_source(root), actual)
    print(format_report(issues, args.branch))
    return 1 if issues else 0


if __name__ == "__main__":
    sys.exit(main())
